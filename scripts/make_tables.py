#!/usr/bin/env python3
"""Emit the three report tables for the RCBR-YOLO arms (A/B/C/D).

All arms are read from runs/arms/<tag>/eval.json (eval_arm.py --splits val,test).
Writes reports/cr_yolo_tables.tex.
"""
from __future__ import annotations

import argparse
import json
import statistics as st
import sys
from pathlib import Path

TASK = Path(__file__).resolve().parent
ROOT = TASK.parent
sys.path.insert(0, str(ROOT / "src"))

import paths  # noqa: E402

OUT = paths.REPORTS / "cr_yolo_tables.tex"
BUD = ("0.05", "0.1", "0.2", "0.5", "1.0", "2.0", "5.0")
BETA = 0.5
SEEDS = (42, 43, 44)
COST = {"A": ("21.79", "74.4"), "B": ("22.36", "80.0"), "C": ("21.79", "74.4"), "D": ("22.36", "80.0")}
def model_name(arm: str, beta: float) -> str:
    if arm == "A":
        return "A: YOLO26m (plain)"
    if arm == "B":
        return "B: + MRC"
    if arm == "C":
        return f"C: + CHBR ($\\beta$={beta:g})"
    return f"D: + both ($\\beta$={beta:g})"


def avg(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def pct(v, nd=1):
    return "--" if v is None else f"{100 * v:.{nd}f}"


def load(arm: str, seed: int, beta: float = BETA) -> dict | None:
    tag = f"{arm}_s{seed}" + (f"_b{beta:g}" if arm in ("C", "D") else "")
    p = paths.RUNS / "arms" / tag / "eval.json"
    if not p.is_file():
        return None
    e = json.loads(p.read_text(encoding="utf-8"))
    return {"val": e["val"]["budgets"], "test": e["test"]["budgets"],
            "val_ap": e["val"]["map_nms07"], "test_ap": e["test"]["map_nms07"],
            "val_c25": e["val"]["fixed_conf_0.25"], "test_c25": e["test"]["fixed_conf_0.25"]}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--beta", type=float, default=BETA)
    ap.add_argument("--seeds", default=",".join(str(s) for s in SEEDS))
    args = ap.parse_args()
    beta = args.beta
    seeds = tuple(int(s) for s in args.seeds.split(",") if s.strip())
    data = {}
    for arm in ("A", "B", "C", "D"):
        data[arm] = {s: d for s in seeds if (d := load(arm, s, beta)) is not None}

    L = ["% ============================================================",
         "% CR-YOLO arms (A/B/C/D) -- generated by src/make_tables.py; do not edit by hand.",
         f"% beta = {beta:g}; seeds {list(seeds)}; only arms with complete runs are emitted.",
         "% ============================================================", ""]

    # ---------------- Table 1
    L += [r"\begin{table*}[t]", r"\centering",
          r"\caption{Conventional object detection performance of the CR-YOLO arms on the "
          r"ShoePrint test set.}", r"\label{tab:cr_detection}", r"\small",
          r"\setlength{\tabcolsep}{5pt}", "", r"\resizebox{\textwidth}{!}{%",
          r"\begin{tabular}{lccccccccccc}", r"\toprule",
          "Model & Input size & P (\\%) $\\uparrow$ & R (\\%) $\\uparrow$ & F$_1$ (\\%) $\\uparrow$ "
          "& F$_2$ (\\%) $\\uparrow$ & mAP$_{50}$ (\\%) $\\uparrow$ & mAP$_{75}$ (\\%) $\\uparrow$ "
          "& mAP$_{50:95}$ (\\%) $\\uparrow$ & Params (M) $\\downarrow$ & FLOPs (G) $\\downarrow$ "
          "& Latency (ms) $\\downarrow$ \\\\", r"\midrule"]
    for arm, per in data.items():
        if not per:
            continue
        rows = list(per.values())
        P = avg([r["test_c25"]["precision"] for r in rows])
        R = avg([r["test_c25"]["recall"] for r in rows])
        F1 = avg([2 * r["test_c25"]["precision"] * r["test_c25"]["recall"]
                  / (r["test_c25"]["precision"] + r["test_c25"]["recall"]) for r in rows])
        F2 = avg([r["test_c25"]["f2"] for r in rows])
        AP50 = avg([r["test_ap"]["AP50"] for r in rows])
        AP75 = avg([r["test_ap"]["AP75"] for r in rows])
        AP = avg([r["test_ap"]["AP"] for r in rows])
        L.append(f"{model_name(arm, beta)} & 640 & {pct(P)} & {pct(R)} & {pct(F1)} & {pct(F2)} & "
                 f"{pct(AP50)} & {pct(AP75)} & {pct(AP)} & {COST[arm][0]} & {COST[arm][1]} & -- \\\\")
    L += [r"\bottomrule", r"\end{tabular}%", "}", "", r"\vspace{2pt}",
          r"\parbox{\textwidth}{\footnotesize",
          r"\textit{Note:} P, R, F$_1$, and F$_2$ are micro-averaged over all evaluated instances at "
          r"a confidence threshold of 0.25 and a box-matching IoU threshold of 0.50. "
          r"mAP$_{50:95}$ averages IoU thresholds 0.50--0.95 (step 0.05); for mAP, predictions are "
          r"retained with the protocol score threshold (0.001) rather than truncated at 0.25 "
          r"(pycocotools, \texttt{maxDets}=100, after class-aware NMS at IoU 0.7). Only the "
          r"\textit{pinhole} category has ground truth, so the micro-average equals the pinhole "
          r"metrics. All arms share one recipe (640, 80 epochs, mosaic disabled, fixed "
          r"\texttt{last.pt}, the reported seeds); A, B, C, D differ only in the context blocks and the "
          r"ranking term (one-to-many branch, $\beta$ selected on validation only). Params and FLOPs "
          r"were measured on the integrated models (torch.profiler, FP16, 640, batch 1); the "
          r"baseline table reports 75.0 G for the same architecture from a different counter. "
          r"Latency was not measured under a common timing protocol and is omitted.", "}",
          r"\end{table*}", ""]

    # ---------------- Table 2
    L += [r"\begin{table*}[t]", r"\centering",
          r"\caption{Test-set detection performance at operating points selected under different "
          r"validation-set FPPI budgets.}", r"\label{tab:cr_fppi_budget_results}", r"\small",
          r"\setlength{\tabcolsep}{4pt}", "", r"\resizebox{\textwidth}{!}{%",
          r"\begin{tabular}{lccccccc}", r"\toprule",
          r"& \multicolumn{7}{c}{Validation-set FPPI budget} \\", r"\cmidrule(lr){2-8}",
          "Model & 0.05 & 0.1 & 0.2 & 0.5 & 1.0 & 2.0 & 5.0 \\\\", r"\midrule"]
    for arm, per in data.items():
        if not per:
            continue
        rows = list(per.values())
        cells = []
        for b in BUD:
            f = avg([r["test"][b]["fppi"] for r in rows if r["test"][b]])
            rr = avg([r["test"][b]["recall"] for r in rows if r["test"][b]])
            f2 = avg([r["test"][b]["f2"] for r in rows if r["test"][b]])
            cells.append(f"{f:.3f} / {100 * rr:.1f} / {100 * f2:.1f}")
        L.append(f"{model_name(arm, beta)} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}%", "}", "", r"\vspace{2pt}",
          r"\parbox{\textwidth}{\footnotesize",
          r"\textit{Note:} Each cell reports test-set actual FPPI / micro-averaged recall (\%) / "
          r"F$_2$ (\%). The column headings are validation-set FPPI budgets, not test-set FPPI or "
          r"confidence thresholds; for each model and budget the threshold is selected on the "
          r"validation set and then frozen for testing. Actual test FPPI may exceed the budget and "
          r"is reported as measured. Values are means over the reported seeds; matching uses class-specific "
          r"boxes at IoU 0.50.", "}", r"\end{table*}", ""]

    # ---------------- Table 3
    L += [r"\begin{table*}[t]", r"\centering",
          r"\caption{Detailed operating-point records for different validation-set FPPI budgets.}",
          r"\label{tab:cr_fppi_operating_point_details}", r"\scriptsize",
          r"\setlength{\tabcolsep}{3.5pt}", "", r"\resizebox{\textwidth}{!}{%",
          r"\begin{tabular}{llccccccccc}", r"\toprule",
          "Model & Val. budget & Conf. threshold & Val. FPPI & Test FPPI & Test P (\\%) & "
          "Test R (\\%) & Test F$_2$ (\\%) & Test TP & Test FP & Test FN \\\\", r"\midrule"]
    arms = [a for a in ("A", "B", "C", "D") if data[a]]
    for ai, arm in enumerate(arms):
        rows = list(data[arm].values())
        for j, b in enumerate(BUD):
            th = avg([r["test"][b]["val_threshold"] for r in rows if r["test"][b]])
            vf = avg([r["val"][b]["fppi"] for r in rows if r["val"][b]])
            tf = avg([r["test"][b]["fppi"] for r in rows if r["test"][b]])
            tp = avg([r["test"][b]["precision"] for r in rows if r["test"][b]])
            tr = avg([r["test"][b]["recall"] for r in rows if r["test"][b]])
            tf2 = avg([r["test"][b]["f2"] for r in rows if r["test"][b]])
            ntp = avg([r["test"][b]["tp"] for r in rows if r["test"][b]])
            nfp = avg([r["test"][b]["fp"] for r in rows if r["test"][b]])
            nfn = avg([r["test"][b]["fn"] for r in rows if r["test"][b]])
            name = model_name(arm, beta) if j == 0 else ""
            L.append(f"{name} & {b} & {th:.3f} & {vf:.3f} & {tf:.3f} & {pct(tp)} & {pct(tr)} & "
                     f"{pct(tf2)} & {ntp:.0f} & {nfp:.0f} & {nfn:.0f} \\\\")
        if ai != len(arms) - 1:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}%", "}", "", r"\vspace{2pt}",
          r"\parbox{\textwidth}{\footnotesize",
          r"\textit{Note:} Val.\ denotes the validation set. For each model and FPPI budget the "
          r"confidence threshold is selected on the validation set to maximise recall subject to the "
          r"budget (ties: lower FPPI first; equal-score predictions are kept as one group). Test P, "
          r"R, and F$_2$ are pooled over all instances; TP, FP, and FN are the corresponding "
          r"instance counts and satisfy TP+FN $=$ 352 at every budget. Matching uses class-specific "
          r"boxes at IoU 0.50. Test thresholds are not readjusted on test. Each row is the mean over "
          r"three seeds, so thresholds and FPPI values are averages and counts are rounded.", "}",
          r"\end{table*}", ""]

    text = "\n".join(L) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("written", OUT, len(text), "bytes;", text.count("begin{table*}"), "tables")
    for arm in arms:
        rows = list(data[arm].values())
        print(f"{arm}: n={len(rows)} test mAP {100 * avg([r['test_ap']['AP'] for r in rows]):.1f} "
              f"R@0.05 {100 * avg([r['test']['0.05']['recall'] for r in rows]):.1f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
